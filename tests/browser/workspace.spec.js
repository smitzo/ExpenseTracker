import { test, expect } from '@playwright/test';
test('demo workspace supports transaction entry edit archive and navigation', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/?demo=1');
  await expect(page.getByRole('heading', { name: 'Your money, at a glance.' })).toBeVisible();
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Description', { exact: true }).fill('Browser coffee');
  await dialog.getByLabel('Amount (INR)').fill('125.29');
  await dialog.getByRole('button', { name: 'Save transaction' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('link', { name: 'Transactions', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search transactions' }).fill('Browser coffee');
  await expect(page.getByRole('cell', { name: 'Browser coffee', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Browser coffee', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Description', { exact: true }).fill('Edited coffee');
  await page.getByRole('button', { name: 'Save transaction', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search transactions' }).fill('Edited coffee');
  await expect(page.getByRole('cell', { name: 'Edited coffee', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Archive Edited coffee', exact: true }).click();
  await page.getByRole('button', { name: 'Archive entry', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Edited coffee', exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('budget and recurring editors save reviewed plans', async ({ page }) => {
  await page.goto('/?demo=1#budgets');
  await page.getByRole('button', { name: 'Set a budget' }).click();
  await page.getByLabel('Monthly limit').fill('4500.29');
  await page.getByRole('button', { name: 'Save budget' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('link', { name: 'Recurring', exact: true }).click();
  await page.getByRole('button', { name: 'Add a plan' }).click();
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Yoga class');
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('1200');
  await page.getByRole('button', { name: 'Save plan' }).click();
  await expect(page.getByText('Yoga class', { exact: true })).toBeVisible();
});
